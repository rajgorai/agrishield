# Load class names
with open('models/class_names.json', 'r', encoding='utf-8') as f:
    class_names_dict = json.load(f)

# Build SQL
sql_lines = []
sql_lines.append("-- ========================================")
sql_lines.append("-- UPDATE TREATMENTS WITH REAL ADVISORIES")
sql_lines.append("-- ========================================")
sql_lines.append("BEGIN;")
sql_lines.append("")

missing = []
for idx, class_name in class_names_dict.items():
    if class_name in TREATMENTS:
        severity, en, bn, hi = TREATMENTS[class_name]
        # Escape single quotes
        en_escaped = en.replace("'", "''")
        bn_escaped = bn.replace("'", "''")
        hi_escaped = hi.replace("'", "''")
        sql_lines.append(
            f"UPDATE diseases SET severity = '{severity}', "
            f"treatment_en = '{en_escaped}', "
            f"treatment_bn = '{bn_escaped}', "
            f"treatment_hi = '{hi_escaped}' "
            f"WHERE model_class_label = '{class_name}';"
        )
    else:
        missing.append(class_name)

sql_lines.append("")
sql_lines.append("COMMIT;")

# Write
with open('update_treatments.sql', 'w', encoding='utf-8') as f:
    f.write('\n'.join(sql_lines))

